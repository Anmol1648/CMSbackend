import fs from 'fs/promises';
import path from 'path';
import { v2 as cloudinary } from 'cloudinary';

/**
 * Where file bytes live. Rows in `files` describe them; this only stores and fetches bytes by key.
 * STORAGE_PROVIDER=local (default) keeps them under STORAGE_DIR (./storage); cloudinary uploads them.
 */
export interface StorageProvider {
    readonly name: 'local' | 'cloudinary';
    put(key: string, data: Buffer, mimeType: string): Promise<string>;
    get(key: string): Promise<Buffer>;
    remove(key: string): Promise<void>;
}

class LocalStorage implements StorageProvider {
    readonly name = 'local' as const;
    constructor(private root: string) {}

    private pathFor(key: string) {
        const full = path.resolve(this.root, key);
        // Keys are generated by us, but never let one escape the storage folder.
        if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new Error('Invalid storage key');
        return full;
    }

    async put(key: string, data: Buffer) {
        const full = this.pathFor(key);
        await fs.mkdir(path.dirname(full), { recursive: true });
        await fs.writeFile(full, data);
        return key;
    }

    async get(key: string) {
        return fs.readFile(this.pathFor(key));
    }

    async remove(key: string) {
        await fs.rm(this.pathFor(key), { force: true });
    }
}

class CloudinaryStorage implements StorageProvider {
    readonly name = 'cloudinary' as const;
    constructor() {
        cloudinary.config({
            cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
            api_key: process.env.CLOUDINARY_API_KEY,
            api_secret: process.env.CLOUDINARY_API_SECRET,
            secure: true,
        });
    }

    async put(key: string, data: Buffer) {
        const publicId = key.replace(/\.[a-z0-9]+$/i, '');
        await new Promise<void>((resolve, reject) =>
            cloudinary.uploader
                .upload_stream({ public_id: publicId, resource_type: 'raw', overwrite: true, type: 'authenticated' }, (err) => (err ? reject(err) : resolve()))
                .end(data)
        );
        return publicId;
    }

    async get(key: string) {
        const url = cloudinary.url(key, { resource_type: 'raw', type: 'authenticated', sign_url: true });
        const res = await fetch(url);
        if (!res.ok) throw new Error(`Cloudinary download failed (${res.status})`);
        return Buffer.from(await res.arrayBuffer());
    }

    async remove(key: string) {
        await cloudinary.uploader.destroy(key, { resource_type: 'raw', type: 'authenticated' });
    }
}

let provider: StorageProvider | undefined;

export const storage = (): StorageProvider =>
    (provider ??=
        process.env.STORAGE_PROVIDER === 'cloudinary'
            ? new CloudinaryStorage()
            : new LocalStorage(process.env.STORAGE_DIR || path.join(process.cwd(), 'storage')));

/** Tests point storage at a temporary folder. */
export const useStorageForTests = (p: StorageProvider) => {
    provider = p;
};
export const localStorageAt = (dir: string): StorageProvider => new LocalStorage(dir);
