import { db } from '../../core/db';
import { getUserAccess } from '../rbac/access.service';
import { defineDataSource, isoDay, personName, titleCase, yearsSince } from '../reports/datasources.registry';

/** Staff for the Report Builder: one row per staff member. */

const name = { select: { name: true } } as const;

defineDataSource({
    key: 'staff',
    label: 'Staff',
    description: 'Every staff member: post, department, joining, contact, bank and PF details (sensitive ones only for those allowed).',
    category: 'Staff',
    permissions: ['staff.view'],
    sensitivePermission: 'staff.view_sensitive',
    params: [],
    fields: [
        { key: 'employeeCode', label: 'Employee code', type: 'text' },
        { key: 'name', label: 'Name', type: 'text' },
        { key: 'status', label: 'Status', type: 'text' },
        { key: 'designation', label: 'Designation', type: 'text', group: 'Post' },
        { key: 'department', label: 'Department', type: 'text', group: 'Post' },
        { key: 'staffType', label: 'Teaching / non-teaching', type: 'text', group: 'Post' },
        { key: 'teachingPost', label: 'Teaching post (PRT / TGT / PGT)', type: 'text', group: 'Post' },
        { key: 'employmentType', label: 'Employment type', type: 'text', group: 'Post' },
        { key: 'joiningDate', label: 'Joining date', type: 'date', group: 'Post' },
        { key: 'yearsOfService', label: 'Years of service', type: 'number', group: 'Post' },
        { key: 'reportsTo', label: 'Reports to', type: 'text', group: 'Post' },
        { key: 'classTeacherOf', label: 'Class teacher of', type: 'text', group: 'Post' },
        { key: 'gender', label: 'Gender', type: 'text', group: 'Personal' },
        { key: 'dateOfBirth', label: 'Date of birth', type: 'date', group: 'Personal' },
        { key: 'age', label: 'Age (years)', type: 'number', group: 'Personal' },
        { key: 'bloodGroup', label: 'Blood group', type: 'text', group: 'Personal' },
        { key: 'religion', label: 'Religion', type: 'text', group: 'Personal' },
        { key: 'casteCategory', label: 'Caste category', type: 'text', group: 'Personal' },
        { key: 'maritalStatus', label: 'Marital status', type: 'text', group: 'Personal' },
        { key: 'aadhaar', label: 'Aadhaar', type: 'text', group: 'Personal', sensitive: true },
        { key: 'pan', label: 'PAN', type: 'text', group: 'Personal', sensitive: true },
        { key: 'mobile', label: 'Mobile', type: 'text', group: 'Contact' },
        { key: 'email', label: 'Email', type: 'text', group: 'Contact' },
        { key: 'address', label: 'Address', type: 'text', group: 'Contact' },
        { key: 'city', label: 'City / town', type: 'text', group: 'Contact' },
        { key: 'district', label: 'District', type: 'text', group: 'Contact' },
        { key: 'state', label: 'State', type: 'text', group: 'Contact' },
        { key: 'pinCode', label: 'PIN code', type: 'text', group: 'Contact' },
        { key: 'emergencyName', label: 'Emergency contact', type: 'text', group: 'Contact' },
        { key: 'emergencyPhone', label: 'Emergency phone', type: 'text', group: 'Contact' },
        { key: 'bank', label: 'Bank', type: 'text', group: 'Bank and PF' },
        { key: 'bankAccountNo', label: 'Bank account no.', type: 'text', group: 'Bank and PF', sensitive: true },
        { key: 'ifsc', label: 'IFSC', type: 'text', group: 'Bank and PF' },
        { key: 'pfNumber', label: 'PF number', type: 'text', group: 'Bank and PF', sensitive: true },
        { key: 'uan', label: 'UAN', type: 'text', group: 'Bank and PF' },
        { key: 'leftOn', label: 'Relieved / status date', type: 'date' },
        { key: 'relievingReason', label: 'Relieving reason', type: 'text' },
        { key: 'hasLogin', label: 'Has a login', type: 'boolean' },
    ],
    async load(_p, ctx) {
        const access = await getUserAccess(ctx.userId);
        const own = access.permissions['staff.view'] !== 'all';
        const staff = await db.staff.findMany({
            where: own ? { userId: ctx.userId } : {},
            orderBy: [{ firstName: 'asc' }, { lastName: 'asc' }],
            include: {
                gender: name, bloodGroup: name, religion: name, casteCategory: name, maritalStatus: name, state: name, district: name, city: name,
                department: name, designation: name, staffType: name, employmentType: name, teachingPost: name, bank: name, relievingReason: name,
                reportsTo: { select: { firstName: true, middleName: true, lastName: true } },
                classTeacherOf: { where: { academicYear: { isCurrent: true } }, select: { name: true, schoolClass: { select: { name: true, shortName: true } } } },
            },
        });
        return staff.map((s) => ({
            _id: s.id,
            employeeCode: s.employeeCode,
            name: personName(s),
            status: titleCase(s.status),
            designation: s.designation?.name ?? null,
            department: s.department?.name ?? null,
            staffType: s.staffType?.name ?? null,
            teachingPost: s.teachingPost?.name ?? null,
            employmentType: s.employmentType?.name ?? null,
            joiningDate: isoDay(s.joiningDate),
            yearsOfService: yearsSince(s.joiningDate),
            reportsTo: personName(s.reportsTo),
            classTeacherOf: s.classTeacherOf.map((x) => `${x.schoolClass.shortName ?? x.schoolClass.name}-${x.name}`).join(', ') || null,
            gender: s.gender?.name ?? null,
            dateOfBirth: isoDay(s.dateOfBirth),
            age: yearsSince(s.dateOfBirth),
            bloodGroup: s.bloodGroup?.name ?? null,
            religion: s.religion?.name ?? null,
            casteCategory: s.casteCategory?.name ?? null,
            maritalStatus: s.maritalStatus?.name ?? null,
            aadhaar: s.aadhaar,
            pan: s.pan,
            mobile: s.mobile,
            email: s.email,
            address: s.addressLine,
            city: s.city?.name ?? null,
            district: s.district?.name ?? null,
            state: s.state?.name ?? null,
            pinCode: s.pinCode,
            emergencyName: s.emergencyName,
            emergencyPhone: s.emergencyPhone,
            bank: s.bank?.name ?? null,
            bankAccountNo: s.bankAccountNo,
            ifsc: s.ifsc,
            pfNumber: s.pfNumber,
            uan: s.uan,
            leftOn: isoDay(s.statusDate),
            relievingReason: s.relievingReason?.name ?? null,
            hasLogin: !!s.userId,
        }));
    },
});
